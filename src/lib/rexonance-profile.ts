// A chapter heading may be followed by its text directly or after a blank
// line (the owner writes both).
export const REXONANCE_PROFILE_SECTIONS = [...REXONANCE_PROFILE_TEXT.matchAll(
  /【\u3000([^】]+?)\u3000】\n+([\s\S]*?)(?=\n+【\u3000|$)/g,
)].map((match) => ({ title: match[1], body: match[2] }));

export function rexonanceSection(title: string): string[] {
  return (REXONANCE_PROFILE_SECTIONS.find((section) => section.title === title)?.body ?? "")
    .split("\n").filter((line) => line.length > 0);
}

/** An entry: its heading's name (『 NAME 』, 《 NAME 》 or ⬛︎ NAME), the
 * heading's own parenthesis after 』 when it has one (『 i-2 』（第2世代・…）),
 * and its text. */
export type RexonanceEntry = { name: string; note?: string; body: string };
export function rexonanceEntries(title: string): RexonanceEntry[] {
  const body = REXONANCE_PROFILE_SECTIONS.find((section) => section.title === title)?.body ?? "";
  return [
    ...body.matchAll(
      /(?:^|\n)(?:『 (.+?) 』(?:（(.+?)）)?|《 (.+?) 》|⬛︎ ?(.+?))\n+([\s\S]*?)(?=\n+(?:『 |《 |⬛︎)|$)/g,
    ),
  ].map((match) => ({
    name: match[1] ?? match[3] ?? match[4],
    ...(match[2] ? { note: match[2] } : null),
    body: match[5],
  }));
}
