/** The one sentence on the ウルトラ gain (this site's, `added`): its figures are
 * computed from the table's rows, never typed, so a change to a form's
 * setting moves them with it. */
const figures = (row: readonly string[]) =>
  row.slice(1).map((cell) => Number.parseFloat(cell.replace(/[^\d.]/g, "")));
const [standardPunch, standardKick, standardJump, standardRun] = figures(ROW_STANDARD);
const [ultraPunch, ultraKick, ultraJump, ultraRun] = figures(ROW_ULTRA);
const [farPunch, farKick, , farRun] = figures(ROW_FAR_FROM);
const gain = (to: number, from: number) => (((to - from) / from) * 100).toFixed(2);
const short = (from: number, to: number) => ((1 - from / to) * 100).toFixed(2);
const ULTRA_GAIN = `イリュージョンクルム・ウルトラへ移行した場合、通常形態と比較してパンチ力は${gain(ultraPunch, standardPunch)}%、キック力は${gain(ultraKick, standardKick)}%、ジャンプ力は${Math.round(((ultraJump - standardJump) / standardJump) * 100)}%向上し、100m走行速度は約${(standardRun / ultraRun).toFixed(2)}倍となる。ファーフロムとの比較では、パンチ力が${short(ultraPunch, farPunch)}%、キック力が${short(ultraKick, farKick)}%、走行速度が約${short(farRun, ultraRun)}%下回る。`;

