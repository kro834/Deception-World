import { META_UNITAS_PERFORMANCE } from "./meta-unitas-data";
import { jp } from "./meta-unitas-parts";

/* META UNITAS SAGA — #performance: the owner's comparison (2026-10-23), its
   Meta Unitas parts, as meta-unitas-data.ts holds them (generated by
   scripts/build-meta-unitas-data.mjs: Rexonance removed by deletion only,
   ULTRA's computation row supplied, the provisos dropped). The tables carry
   the comparison: each value cell draws its share of the column's best as a
   bar (the 100 m column on a log scale, faster longer), and the two Meta
   Unitas rows stand out in the form's own light. #p16 is the P14・P16
   chapter. */

type Chapter = (typeof META_UNITAS_PERFORMANCE.chapters)[number];

/** A cell's number (205.6t〜 → 205.6; 50000〜YOPS → 50000). */
const valueOf = (cell: string) => {
  const match = /^([\d.]+)/.exec(cell);
  return match ? Number(match[1]) : Number.NaN;
};

/** Each column's bar shares (0 … 1), or null for a column without numbers. */
function columnShares(rows: readonly (readonly string[])[], column: number, head: string) {
  const values = rows.map((row) => valueOf(row[column]));
  if (values.some((value) => !Number.isFinite(value))) return null;
  if (/走力|秒/.test(head)) {
    // Time: shorter is faster. log(1/t), from the slowest to the fastest.
    const speeds = values.map((value) => Math.log10(1 / value));
    const min = Math.min(...speeds) - 0.35;
    const max = Math.max(...speeds);
    return speeds.map((speed) => (speed - min) / (max - min));
  }
  const max = Math.max(...values);
  return values.map((value) => value / max);
}

const isMetaUnitas = (name: string) => name.startsWith("メタ・ウニタス");

function ComparisonTable({ chapter }: { chapter: Chapter }) {
  const table = chapter.table;
  if (!table) return null;
  const shares = table.head.map((head, column) =>
    column === 0 ? null : columnShares(table.rows, column, head),
  );
  return (
    <div className="mus-table-wrap rxs-reveal">
      <table className="mus-table">
        <caption className="visually-hidden">{chapter.title}</caption>
        <thead>
          <tr>
            {table.head.map((head, column) => (
              <th key={head} scope="col" className={column === 0 ? "is-name" : undefined}>
                {jp(head)}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {table.rows.map((row, rowIndex) => (
            <tr
              key={row[0]}
              data-self={isMetaUnitas(row[0]) || undefined}
              data-ultra={row[0].endsWith("ULTRA") || undefined}
            >
              {row.map((cell, column) =>
                column === 0 ? (
                  <th key={column} scope="row">
                    {jp(cell)}
                  </th>
                ) : (
                  <td
                    key={column}
                    style={
                      shares[column]
                        ? { ["--mus-bar" as string]: shares[column]![rowIndex].toFixed(3) }
                        : undefined
                    }
                    data-bar={shares[column] ? "true" : undefined}
                  >
                    <span>{jp(cell)}</span>
                  </td>
                ),
              )}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** The P16 paragraph's four figures, set large where they stand. */
function withFigures(text: string) {
  const parts = text.split(/(\d+%(?:向上|短縮|削減))/u);
  return parts.map((part, index) =>
    index % 2 === 1 ? (
      <b key={index} className="mus-figure">
        {part}
      </b>
    ) : (
      part
    ),
  );
}

export function MetaUnitasPerformance() {
  const { chapters, lineup } = META_UNITAS_PERFORMANCE;
  return (
    <div className="mus-performance">
      <p className="mus-lineup" lang="en">
        {jp(lineup)}
      </p>
      {chapters.map((chapter) => {
        const isP16 = chapter.title.startsWith("P14");
        return (
          <article
            key={chapter.title}
            id={isP16 ? "p16" : undefined}
            className={`mus-compare${chapter.table ? " has-table" : ""}`}
            aria-labelledby={`mus-compare-${chapters.indexOf(chapter)}`}
          >
            <h3 id={`mus-compare-${chapters.indexOf(chapter)}`} className="rxs-reveal">
              {jp(chapter.title)}
            </h3>
            <ComparisonTable chapter={chapter} />
            {chapter.body.length ? (
              <div className="mus-copy rxs-reveal">
                {chapter.body.map((paragraph, index) => (
                  <p key={index}>{isP16 ? withFigures(paragraph) : paragraph}</p>
                ))}
              </div>
            ) : null}
          </article>
        );
      })}
    </div>
  );
}
