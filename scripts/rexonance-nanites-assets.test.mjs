const BUDGET = { cells: 62_000, comets: 12_000, fx: 45_000, guide: 150_000 };
const decode = async (src) => {
  const { data, info } = await sharp(publicFile(src)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
};
const luminance = (d, i) => (0.2126 * d[i] + 0.7152 * d[i + 1] + 0.0722 * d[i + 2]) / 255;
const seamLoops = (id) => {
  const bytes = Buffer.from(REXONANCE_NANITE_SEAMS[id], "base64");
  const words = Array.from({ length: bytes.length / 2 }, (_, i) => bytes.readInt16LE(i * 2));
  const loops = [];
  let at = 1;
  for (let l = 0; l < words[0]; l += 1) {
    const n = words[at++];
    loops.push(Array.from({ length: n }, () => [words[at++] / 4, words[at++] / 4]));
  }
  assert.equal(at, words.length, `${id}: the seam's words are exactly its loops`);
  return loops;
};

test("the kit's folder holds exactly its four sheets, at their sizes and within budget", async () => {
  const folder = readdirSync(publicFile(REXONANCE_NANITE_DIR)).sort();
  assert.deepEqual(folder, ["cells.webp", "comets.webp", "fx.webp", "guide.webp"]);
  let total = 0;
  for (const [name, sheet] of Object.entries(SHEETS)) {
    assert.equal(sheet.src, `${REXONANCE_NANITE_DIR}/${name}.webp`);
    const meta = await sharp(publicFile(sheet.src)).metadata();
    assert.equal(meta.format, "webp");
    assert.deepEqual([meta.width, meta.height, meta.channels], [sheet.width, sheet.height, 4], name);
    const bytes = statSync(publicFile(sheet.src)).size;
    assert.equal(REXONANCE_NANITE_BYTES[name], bytes, `${name}: BYTES is the file's size`);
    assert.ok(bytes <= BUDGET[name], `${name}.webp ${bytes} B within ${BUDGET[name]}`);
    total += bytes;
  }
  assert.equal(REXONANCE_NANITE_BYTES.total, total);
  assert.ok(total <= 280_000, `the kit is ${total} B`);
  assert.deepEqual(REXONANCE_NANITE_ASSETS, Object.values(SHEETS).map((sheet) => sheet.src));
  assert.deepEqual(Object.keys(REXONANCE_NANITES), ["cells", "comets", "fx", "guide", "seams", "goldBoxes"]);
  assert.equal(REXONANCE_NANITES.seams, REXONANCE_NANITE_SEAMS);
  assert.equal(REXONANCE_NANITES.goldBoxes, REXONANCE_NANITE_GOLD_BOXES);
});

