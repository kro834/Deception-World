test("every sprite region lies inside its sheet and no two overlap", () => {
  const regions = [];
  const add = (sheet, name, x, y, w, h) => regions.push({ sheet, name, x, y, w, h });
  const c = REXONANCE_NANITE_CELLS;
  for (let t = 0; t < 4; t += 1)
    for (let f = 0; f < c.frames; f += 1) {
      add("cells", `tumble ${t}/${f}`, c.cell * f, c.cell * t, c.cell, c.cell);
      add("cells", `mip ${t}/${f}`, c.mip.x[t] + c.mip.cell * f, c.mip.y[t], c.mip.cell, c.mip.cell);
    }
  for (let t = 0; t < 3; t += 1)
    for (let k = 0; k < c.unfold.frames; k += 1) add("cells", `unfold ${t}/${k}`, c.unfold.x[t] + c.cell * k, c.unfold.y, c.cell, c.cell);
  for (let t = 0; t < 4; t += 1) add("cells", `bokeh ${t}`, c.bokeh.x[t], c.bokeh.y[t], c.cell, c.cell);
  for (let k = 0; k < c.bead.frames; k += 1) add("cells", `bead ${k}`, c.bead.x + c.cell * k, c.bead.y, c.cell, c.cell);
  for (let k = 0; k < c.spark.frames; k += 1) add("cells", `spark ${k}`, c.spark.x + c.cell * k, c.spark.y, c.cell, c.cell);
  const m = REXONANCE_NANITE_COMETS;
  for (const row of Object.values(m.rows))
    for (let length = 0; length < 2; length += 1)
      for (let a = 0; a < m.angles; a += 1) add("comets", `comet ${row}/${length}/${a}`, m.cell * a, m.cell * (row + length), m.cell, m.cell);
  const { clamp, latch, scan, drop, shock } = REXONANCE_NANITE_FX;
  for (const row of Object.values(clamp.corners))
    for (let f = 0; f < clamp.frames; f += 1) add("fx", `clamp ${row}/${f}`, clamp.x + clamp.cell * f, clamp.y + clamp.cell * row, clamp.cell, clamp.cell);
  for (let f = 0; f < latch.frames; f += 1) add("fx", `latch ${f}`, latch.x + latch.cell * f, latch.y, latch.cell, latch.cell);
  add("fx", "scan", scan.x, scan.y, scan.w, scan.h);
  for (let e = 0; e < drop.elongations.length; e += 1)
    for (let a = 0; a < drop.angles; a += 1) add("fx", `drop ${e}/${a}`, drop.x + drop.cell * a, drop.y + drop.cell * e, drop.cell, drop.cell);
  for (let k = 0; k < shock.frames; k += 1)
    add("fx", `shock ${k}`, shock.x + shock.w * (k % shock.cols), shock.y + shock.h * Math.floor(k / shock.cols), shock.w, shock.h);
  for (const r of regions) {
    const sheet = SHEETS[r.sheet];
    assert.ok(r.x >= 0 && r.y >= 0 && r.x + r.w <= sheet.width && r.y + r.h <= sheet.height, `${r.name} inside ${r.sheet}`);
  }
  for (let i = 0; i < regions.length; i += 1)
    for (let j = i + 1; j < regions.length; j += 1) {
      const [a, b] = [regions[i], regions[j]];
      if (a.sheet !== b.sheet) continue;
      const apart = a.x + a.w <= b.x || b.x + b.w <= a.x || a.y + a.h <= b.y || b.y + b.h <= a.y;
      assert.ok(apart, `${a.name} and ${b.name} overlap`);
    }
});

test("every plate but the driver has its real outline as a seam, starting at its seat", async () => {
  const { data, width } = await decode("/rexonance-suit-20261016/plates.webp");
  assert.deepEqual(Object.keys(REXONANCE_NANITE_SEAMS).sort(), PIECES.map((piece) => piece.id).sort());
  for (const piece of PIECES) {
    const loops = seamLoops(piece.id);
    const points = loops.flat();
    assert.ok(loops.length >= 1 && loops.length <= 3, `${piece.id}: ${loops.length} loops`);
    assert.ok(points.length <= 128, `${piece.id}: ${points.length} points`);
    const inside = points.filter(([x, y]) => x >= piece.x - 1 && y >= piece.y - 1 && x <= piece.x + piece.w + 1 && y <= piece.y + piece.h + 1);
    assert.ok(inside.length >= 8 && inside.length === points.length, `${piece.id}: its seam lies in its box`);
    const area = (loop) => loop.reduce((s, [x0, y0], i) => s + x0 * loop[(i + 1) % loop.length][1] - loop[(i + 1) % loop.length][0] * y0, 0) / 2;
    assert.ok(area(loops[0]) > 0, `${piece.id}: clockwise on screen`);
    for (const loop of loops.slice(1)) assert.ok(area(loop) > 40 && area(loop) <= area(loops[0]), `${piece.id}: islands > 40 px²`);
    // The outline point nearest the seat: the boundary of the art (alpha >
    // 96) component that loop 0 encloses.
    const { ax, ay, w, h, seat } = piece;
    const solid = (i, j) => i >= 0 && j >= 0 && i < w && j < h && data[((ay + j) * width + ax + i) * 4 + 3] > 96;
    const label = new Int32Array(w * h).fill(-1);
    const sizes = [];
    for (let j = 0; j < h; j += 1)
      for (let i = 0; i < w; i += 1) {
        if (!solid(i, j) || label[j * w + i] >= 0) continue;
        const id = sizes.length;
        const stack = [[i, j]];
        label[j * w + i] = id;
        let count = 0;
        while (stack.length) {
          const [x, y] = stack.pop();
          count += 1;
          for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
            const [nx, ny] = [x + dx, y + dy];
            if (solid(nx, ny) && label[ny * w + nx] < 0) {
              label[ny * w + nx] = id;
              stack.push([nx, ny]);
            }
          }
        }
        sizes.push(count);
      }
    const within = (px, py, loop) => {
      let odd = false;
      for (let a = 0, b = loop.length - 1; a < loop.length; b = a++) {
        const [xa, ya] = loop[a];
        const [xb, yb] = loop[b];
        if (ya > py !== yb > py && px < ((xb - xa) * (py - ya)) / (yb - ya) + xa) odd = !odd;
      }
      return odd;
    };
    const votes = new Map();
    for (let j = 0; j < h; j += 2)
      for (let i = 0; i < w; i += 2) {
        const id = label[j * w + i];
        if (id >= 0 && within(i + 0.5 + piece.x, j + 0.5 + piece.y, loops[0])) votes.set(id, (votes.get(id) ?? 0) + 1);
      }
    const component = [...votes].sort((a, b) => b[1] - a[1])[0][0];
    let nearest = null;
    let best = Infinity;
    for (let j = 0; j < h; j += 1)
      for (let i = 0; i < w; i += 1) {
        if (label[j * w + i] !== component) continue;
        if (solid(i - 1, j) && solid(i + 1, j) && solid(i, j - 1) && solid(i, j + 1)) continue;
        const [x, y] = [i + 0.5 + piece.x, j + 0.5 + piece.y];
        const d = Math.hypot(x - seat[0], y - seat[1]);
        if (d < best) [best, nearest] = [d, [x, y]];
      }
    const [p0x, p0y] = loops[0][0];
    const gap = Math.hypot(p0x - nearest[0], p0y - nearest[1]);
    assert.ok(gap <= 6, `${piece.id}: point 0 is ${gap.toFixed(1)} px from the outline point nearest the seat`);
  }
});

test("every plate's gold box bounds exactly its gold cells, inside the plate", () => {
  assert.deepEqual(Object.keys(REXONANCE_NANITE_GOLD_BOXES).sort(), PIECES.filter((p) => REXONANCE_SUIT_GOLD_CELLS[p.id]).map((p) => p.id).sort());
  const G = REXONANCE_SUIT_GOLD_CELL;
  for (const piece of PIECES) {
    const box = REXONANCE_NANITE_GOLD_BOXES[piece.id];
    const bits = Buffer.from(REXONANCE_SUIT_GOLD_CELLS[piece.id], "base64");
    const cols = Math.ceil(piece.w / G);
    let [x0, y0, x1, y1] = [Infinity, Infinity, -Infinity, -Infinity];
    for (let bit = 0; bit < cols * Math.ceil(piece.h / G); bit += 1) {
      if (!(bits[bit >> 3] & (1 << (bit & 7)))) continue;
      const [cx, cy] = [(bit % cols) * G, Math.floor(bit / cols) * G];
      [x0, y0] = [Math.min(x0, cx), Math.min(y0, cy)];
      [x1, y1] = [Math.max(x1, Math.min(piece.w, cx + G)), Math.max(y1, Math.min(piece.h, cy + G))];
    }
    assert.deepEqual(box, [piece.x + x0, piece.y + y0, x1 - x0, y1 - y0], piece.id);
  }
});

test("the hex chips: a lit face-on core, a dark back that still glows, a square slab when unfolded", async () => {
  const { data, width } = await decode(REXONANCE_NANITE_CELLS.src);
  const C = REXONANCE_NANITE_CELLS.cell;
  const stats = (x0, y0, region = () => true) => {
    let [sum, weight] = [0, 0];
    for (let y = 0; y < C; y += 1)
      for (let x = 0; x < C; x += 1) {
        if (!region(x + 0.5 - C / 2, y + 0.5 - C / 2)) continue;
        const i = ((y0 + y) * width + x0 + x) * 4;
        const a = data[i + 3] / 255;
        sum += luminance(data, i) * a;
        weight += a;
      }
    return weight ? sum / weight : 0;
  };
  for (let t = 0; t < 4; t += 1) {
    const centre = stats(0, C * t, (x, y) => Math.hypot(x, y) < 5);
    const border = stats(0, C * t, (x, y) => Math.hypot(x, y) > 10);
    assert.ok(centre > border, `tone ${t}: the lock pose's core (${centre.toFixed(2)}) outshines its rim (${border.toFixed(2)})`);
    const f0 = stats(0, C * t);
    for (let f = 9; f <= 15; f += 1) {
      const back = stats(C * f, C * t);
      assert.ok(back < f0 && back > 8 / 255, `tone ${t} frame ${f}: the back ${back.toFixed(3)} (face ${f0.toFixed(3)})`);
    }
  }
  for (let t = 0; t < 3; t += 1) {
    const x0 = REXONANCE_NANITE_CELLS.unfold.x[t] + C * 6;
    let opaque = 0;
    for (let y = 2; y < 30; y += 1)
      for (let x = 2; x < 30; x += 1) if (data[((REXONANCE_NANITE_CELLS.unfold.y + y) * width + x0 + x) * 4 + 3] >= 240) opaque += 1;
    assert.ok(opaque >= 0.85 * 28 * 28, `tone ${t}: the unfolded slab covers ${opaque} of 784 px`);
    // k0 is the lock pose (the same pixels, up to the lossy encoding).
    let diff = 0;
    for (let y = 0; y < C; y += 1)
      for (let x = 0; x < C; x += 1) {
        const k = ((REXONANCE_NANITE_CELLS.unfold.y + y) * width + REXONANCE_NANITE_CELLS.unfold.x[t] + x) * 4;
        const f = ((C * t + y) * width + x) * 4;
        for (let c = 0; c < 3; c += 1) diff += Math.abs((data[k + c] * data[k + 3]) / 255 - (data[f + c] * data[f + 3]) / 255);
        diff += Math.abs(data[k + 3] - data[f + 3]);
      }
    assert.ok(diff / (C * C * 4) <= 3, `tone ${t}: unfold k0 is tumble f0 (mean difference ${(diff / (C * C * 4)).toFixed(2)})`);
  }
  // The spark's first frame is the largest and brightest.
  const spark = (k) => {
    let sum = 0;
    for (let y = 0; y < C; y += 1)
      for (let x = 0; x < C; x += 1) {
        const i = ((REXONANCE_NANITE_CELLS.spark.y + y) * width + REXONANCE_NANITE_CELLS.spark.x + C * k + x) * 4;
        sum += luminance(data, i) * data[i + 3];
      }
    return sum;
  };
  for (let k = 1; k < 4; k += 1) assert.ok(spark(k) < spark(k - 1), `spark frame ${k} is smaller than ${k - 1}`);
});

test("each comet's head is its brightest pixel, at (16, 16)", async () => {
  const { data, width } = await decode(REXONANCE_NANITE_COMETS.src);
  const { cell, angles, rows, head } = REXONANCE_NANITE_COMETS;
  for (const row of Object.values(rows))
    for (let length = 0; length < 2; length += 1)
      for (let a = 0; a < angles; a += 1) {
        const [x0, y0] = [cell * a, cell * (row + length)];
        const value = (x, y) => {
          const i = ((y0 + y) * width + x0 + x) * 4;
          return luminance(data, i) * data[i + 3];
        };
        let max = 0;
        for (let y = 0; y < cell; y += 1) for (let x = 0; x < cell; x += 1) max = Math.max(max, value(x, y));
        assert.ok(value(head[0], head[1]) >= max - 1, `comet ${row + length}/${a}`);
        // The tail trails the motion: brighter behind the head than ahead.
        const theta = (a * REXONANCE_NANITE_COMETS.step * Math.PI) / 180;
        const at = (d) => value(Math.round(head[0] + Math.cos(theta) * d), Math.round(head[1] + Math.sin(theta) * d));
        assert.ok(at(-5) > at(5), `comet ${row + length}/${a}: its tail runs along -θ`);
      }
});

test("the guideway conduit stays on each plate's own gold, covers it, and is lit from the upper left", async () => {
  const guide = await decode(REXONANCE_NANITE_GUIDE.src);
  const gold = await decode(REXONANCE_SUIT_GOLD_ATLAS.src);
  const plates = await decode("/rexonance-suit-20261016/plates.webp");
  const W = guide.width;
  const H = guide.height;
  // gold α > 32, dilated by 2 px, inside the non-driver cells.
  const allowed = new Uint8Array(W * H);
  const figure = new Uint8Array(W * H);
  for (const { ax, ay, w, h } of PIECES)
    for (let y = ay; y < ay + h; y += 1)
      for (let x = ax; x < ax + w; x += 1) {
        for (let dy = -2; dy <= 2; dy += 1)
          for (let dx = -2; dx <= 2; dx += 1) {
            const [xx, yy] = [x + dx, y + dy];
            if (xx < ax || yy < ay || xx >= ax + w || yy >= ay + h) continue;
            if (dx * dx + dy * dy <= 5 && gold.data[(yy * W + xx) * 4 + 3] > 32) allowed[y * W + x] = 1;
            if (plates.data[(yy * plates.width + xx) * 4 + 3] > 0) figure[y * W + x] = 1;
          }
      }
  let outside = 0;
  let unfigured = 0;
  for (let i = 0; i < W * H; i += 1) {
    if (!guide.data[i * 4 + 3]) continue;
    if (!allowed[i]) outside += 1;
    if (!figure[i]) unfigured += 1;
  }
  assert.equal(outside, 0, "alpha 0 wherever the gold's alpha ≤ 32 (dilated by 2 px), and outside the cells");
  assert.equal(unfigured, 0, "nothing outside the art's alpha");
  // It covers the gold: every gold cell that holds solid trim shows conduit.
  const G = REXONANCE_SUIT_GOLD_CELL;
  let [solid, covered] = [0, 0];
  for (const piece of PIECES) {
    const bits = Buffer.from(REXONANCE_SUIT_GOLD_CELLS[piece.id], "base64");
    const cols = Math.ceil(piece.w / G);
    for (let bit = 0; bit < cols * Math.ceil(piece.h / G); bit += 1) {
      if (!(bits[bit >> 3] & (1 << (bit & 7)))) continue;
      const [cx, cy] = [piece.ax + (bit % cols) * G, piece.ay + Math.floor(bit / cols) * G];
      let [trim, conduit] = [false, false];
      for (let y = cy; y < Math.min(cy + G, piece.ay + piece.h); y += 1)
        for (let x = cx; x < Math.min(cx + G, piece.ax + piece.w); x += 1) {
          if (gold.data[(y * W + x) * 4 + 3] > 160) trim = true;
          if (guide.data[(y * W + x) * 4 + 3] > 0) conduit = true;
        }
      if (!trim) continue;
      solid += 1;
      if (conduit) covered += 1;
    }
  }
  assert.ok(covered >= 0.95 * solid, `the conduit covers ${covered} of ${solid} solid gold cells`);
  // The rails' upper-left flanks outshine their lower-right flanks.
  const alpha = (x, y) => (x < 0 || y < 0 || x >= W || y >= H ? 0 : guide.data[(y * W + x) * 4 + 3]);
  let [ul, ulN, lr, lrN] = [0, 0, 0, 0];
  for (let y = 0; y < H; y += 1)
    for (let x = 0; x < W; x += 1) {
      if (alpha(x, y) < 200) continue;
      const L = luminance(guide.data, (y * W + x) * 4);
      if (alpha(x - 1, y - 1) < 64 && alpha(x + 1, y + 1) >= 200) [ul, ulN] = [ul + L, ulN + 1];
      if (alpha(x + 1, y + 1) < 64 && alpha(x - 1, y - 1) >= 200) [lr, lrN] = [lr + L, lrN + 1];
    }
  assert.ok(ulN > 500 && lrN > 500, "rails on every side");
  assert.ok(ul / ulN > lr / lrN, `upper-left flanks ${(ul / ulN).toFixed(3)} vs lower-right ${(lr / lrN).toFixed(3)}`);
});
