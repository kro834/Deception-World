const file = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const publicFile = (src) => file(`public${src}`);
const moduleText = readFileSync(file("src/lib/far-from-nanites-ultra.ts"), "utf8");
const C = FAR_FROM_ULTRA_NANITE_CELLS;
const SHEETS = { cells: C, comets: FAR_FROM_ULTRA_NANITE_COMETS };
const BUDGET = { cells: 96_000, comets: 14_000, total: 110_000 };
const decode = async (src) => {
  const { data, info } = await sharp(publicFile(src)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
};
const luminance = (d, i) => (0.2126 * d[i] + 0.7152 * d[i + 1] + 0.0722 * d[i + 2]) / 255;

/** Every sprite region of a cells-shaped and a comets-shaped config. */
function regions(cells, comets) {
  const out = [];
  const add = (sheet, name, x, y, w, h) => out.push({ sheet, name, x, y, w, h });
  for (let t = 0; t < 4; t += 1)
    for (let f = 0; f < cells.frames; f += 1) {
      add("cells", `tumble ${t}/${f}`, cells.cell * f, cells.cell * t, cells.cell, cells.cell);
      add("cells", `mip ${t}/${f}`, cells.mip.x[t] + cells.mip.cell * f, cells.mip.y[t], cells.mip.cell, cells.mip.cell);
    }
  for (let t = 0; t < 3; t += 1)
    for (let k = 0; k < cells.unfold.frames; k += 1)
      add("cells", `unfold ${t}/${k}`, cells.unfold.x[t] + cells.cell * k, cells.unfold.y, cells.cell, cells.cell);
  for (let t = 0; t < 4; t += 1) add("cells", `bokeh ${t}`, cells.bokeh.x[t], cells.bokeh.y[t], cells.cell, cells.cell);
  for (let k = 0; k < cells.bead.frames; k += 1) add("cells", `bead ${k}`, cells.bead.x + cells.cell * k, cells.bead.y, cells.cell, cells.cell);
  for (let k = 0; k < cells.spark.frames; k += 1) add("cells", `spark ${k}`, cells.spark.x + cells.cell * k, cells.spark.y, cells.cell, cells.cell);
  for (const row of Object.values(comets.rows))
    for (let length = 0; length < 2; length += 1)
      for (let a = 0; a < comets.angles; a += 1)
        add("comets", `comet ${row}/${length}/${a}`, comets.cell * a, comets.cell * (row + length), comets.cell, comets.cell);
  return out;
}

test("the kit's folder holds exactly its two sheets, at their sizes and within budget", async () => {
  assert.equal(FAR_FROM_ULTRA_NANITE_DIR, "/far-from-nanites-ultra-20261022");
  const folder = readdirSync(publicFile(FAR_FROM_ULTRA_NANITE_DIR)).sort();
  assert.deepEqual(folder, ["cells.webp", "comets.webp"]);
  let total = 0;
  for (const [name, sheet] of Object.entries(SHEETS)) {
    assert.equal(sheet.src, `${FAR_FROM_ULTRA_NANITE_DIR}/${name}.webp`);
    const meta = await sharp(publicFile(sheet.src)).metadata();
    assert.equal(meta.format, "webp");
    assert.deepEqual([meta.width, meta.height, meta.channels, meta.hasAlpha], [sheet.width, sheet.height, 4, true], name);
    const bytes = statSync(publicFile(sheet.src)).size;
    assert.equal(FAR_FROM_ULTRA_NANITE_BYTES[name], bytes, `${name}: BYTES is the file's size`);
    assert.ok(bytes <= BUDGET[name], `${name}.webp ${bytes} B within ${BUDGET[name]}`);
    total += bytes;
  }
  assert.equal(FAR_FROM_ULTRA_NANITE_BYTES.total, total);
  assert.ok(total <= BUDGET.total && total < 300_000, `the kit is ${total} B`);
  assert.deepEqual(FAR_FROM_ULTRA_NANITE_ASSETS, [C.src, FAR_FROM_ULTRA_NANITE_COMETS.src]);
  assert.deepEqual(Object.keys(FAR_FROM_ULTRA_NANITES), ["cells", "comets"]);
  assert.equal(FAR_FROM_ULTRA_NANITES.cells, C);
  assert.equal(FAR_FROM_ULTRA_NANITES.comets, FAR_FROM_ULTRA_NANITE_COMETS);
});

