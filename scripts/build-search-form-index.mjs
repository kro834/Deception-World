#!/usr/bin/env node
// Builds src/components/search/form-archive-index.ts from the two embedded
// Form Archive documents, so the site search lists every archived form with
// its published name and tier line. The documents stay the only source: run
// this after either archive changes (scripts/search-form-index.test.mjs says so).
//   node scripts/build-search-form-index.mjs          write the module
//   node scripts/build-search-form-index.mjs --check  exit 1 when it is stale
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const root = fileURLToPath(new URL("../", import.meta.url));
const target = `${root}src/components/search/form-archive-index.ts`;

const decode = (value) =>
  value
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, " ")
    .trim();

/** One record per `<article class="form-detail">`: its id, h3 name and tier line. */
export function extractArchiveForms(html, archive) {
  const forms = [];
  const article = /<article\b[^>]*\bclass="form-detail[^"]*"[^>]*>/g;
  for (let match = article.exec(html); match; match = article.exec(html)) {
    const id = /\bid="([^"]+)"/.exec(match[0])?.[1];
    const head = html.slice(match.index, match.index + 1200);
    const name = /<h3\b[^>]*>([^<]+)<\/h3>/.exec(head)?.[1];
    const tier = /<h3\b[^>]*>[^<]+<\/h3>\s*<p\b[^>]*>([^<]+)<\/p>/.exec(head)?.[1];
    if (!id || !name) continue;
    forms.push({
      id: id.replace(/^.*detail-/, ""),
      archive,
      name: decode(name),
      tier: tier ? decode(tier) : "",
    });
  }
  return forms;
}

export async function buildFormIndexSource() {
  const forms = ["saga", "realm"].flatMap((archive) =>
    extractArchiveForms(
      readFileSync(`${root}public/${archive}-form-archive-embedded.html`, "utf8"),
      archive,
    ),
  );
  const rows = forms
    .map(
      (form) =>
        `  { id: ${JSON.stringify(form.id)}, archive: ${JSON.stringify(form.archive)}, name: ${JSON.stringify(form.name)}, tier: ${JSON.stringify(form.tier)} },`,
    )
    .join("\n");
  const source = `// Generated by scripts/build-search-form-index.mjs from
// public/{saga,realm}-form-archive-embedded.html. Do not edit by hand.
export type ArchiveForm = {
  id: string;
  archive: "saga" | "realm";
  name: string;
  tier: string;
};

export const FORM_ARCHIVE_FORMS: readonly ArchiveForm[] = [
${rows}
];
`;
  return prettier.format(source, {
    ...(await prettier.resolveConfig(target)),
    parser: "typescript",
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const source = await buildFormIndexSource();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {
      // No module yet: it is stale.
    }
    if (current !== source) {
      console.error("form-archive-index.ts is stale: run node scripts/build-search-form-index.mjs");
      process.exit(1);
    }
    console.log("form-archive-index.ts is current");
  } else {
    writeFileSync(target, source);
    console.log(`wrote ${target}`);
  }
}
