// Portrait thumbnails for the Form Archive's form deck (rx8).
//
// Each form chip in the two embedded archives shows its form's art. The art
// is the first image of the form's detail record (already externalized to
// /archive-media by build-embedded-archives.mjs); this cuts a 240x320 top
// crop of it to public/archive-media/thumbs/<archive>-<form>.webp and writes
// the chip -> thumbnail map between the markers in public/archive-deck.css.
//
//   node scripts/build-archive-thumbs.mjs          write thumbnails and map
//   node scripts/build-archive-thumbs.mjs --check  fail if either is stale
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const deckPath = resolve(root, "public/archive-deck.css");
const thumbDirectory = resolve(root, "public/archive-media/thumbs");
const START = "/* thumbs:start (generated by scripts/build-archive-thumbs.mjs) */";
const END = "/* thumbs:end */";

export function extractChipArt(html) {
  const forms = [];
  for (const [label] of html.matchAll(/<label[^>]*class="form-chip"[^>]*>/g)) {
    const id = label.match(/data-form-id="([^"]+)"/)?.[1];
    if (!id) continue;
    const escaped = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const art = html.match(
      new RegExp(
        `id="(?:realm--)?saga-detail-${escaped}"[\\s\\S]{0,1500}?src="(/archive-media/[^"]+)"`,
      ),
    )?.[1];
    if (!art) throw new Error(`no detail art for form chip ${id}`);
    forms.push({ id, art });
  }
  return forms;
}

export function archiveForms() {
  return ["saga", "realm"].flatMap((archive) =>
    extractChipArt(
      readFileSync(resolve(root, `public/${archive}-form-archive-embedded.html`), "utf8"),
    ).map((form) => ({
      ...form,
      archive,
      thumb: `/archive-media/thumbs/${archive}-${form.id}.webp`,
    })),
  );
}

export function thumbMapSource(forms) {
  const lines = forms.map(
    ({ id, thumb }) =>
      `html[data-embedded-archive] .form-chip[data-form-id="${id}"] { --chip-art: url("${thumb}"); }`,
  );
  return `${START}\n${lines.join("\n")}\n${END}`;
}

function withMap(css, forms) {
  const start = css.indexOf(START);
  const end = css.indexOf(END);
  if (start < 0 || end < start) throw new Error("archive-deck.css has no thumbs markers");
  return css.slice(0, start) + thumbMapSource(forms) + css.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const forms = archiveForms();
  const css = readFileSync(deckPath, "utf8");
  const next = withMap(css, forms);
  const missing = forms.filter(({ thumb }) => !existsSync(resolve(root, `public${thumb}`)));
  if (check) {
    if (next !== css || missing.length) {
      console.error(
        `[archive-thumbs] stale: ${next !== css ? "map " : ""}${missing.map((f) => f.thumb).join(" ")}`,
      );
      process.exit(1);
    }
    console.log(`[archive-thumbs] ${forms.length} thumbnails current`);
  } else {
    const { default: sharp } = await import("sharp");
    mkdirSync(thumbDirectory, { recursive: true });
    for (const { art, thumb } of forms) {
      await sharp(resolve(root, `public${art}`))
        .resize(240, 320, { fit: "cover", position: "top" })
        .webp({ quality: 64 })
        .toFile(resolve(root, `public${thumb}`));
    }
    writeFileSync(deckPath, next);
    console.log(`[archive-thumbs] wrote ${forms.length} thumbnails and the chip map`);
  }
}
