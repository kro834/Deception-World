#!/usr/bin/env node
/** ILLUSIONCULUM's plate flights (2026-11-01): each plate's staged flight as
 * the Rexonance nanite engine plans it for this suit (planAssembly +
 * planAssemblyNanites with ILLUSIONCULUM_ARMOUR_STAGING), written as a small
 * table so the form's director (src/lib/illusionculum-assembly-accents.ts)
 * knows where every plate hovers and the exact moment it locks, without
 * planning the 6000-tile assembly a second time on the device.
 *
 *   node scripts/build-illusionculum-flights.mjs          # write
 *   node scripts/build-illusionculum-flights.mjs --check  # fail when stale
 */
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { format, resolveConfig } from "prettier";
import { planAssembly } from "../src/lib/rexonance-resonance.js";
import { planAssemblyNanites } from "../src/lib/rexonance-assembly-nanites.js";
import { ILLUSIONCULUM_ARMOUR_STAGING } from "../src/lib/illusionculum-choreography.ts";
import {
  ILLUSIONCULUM_SUIT_DRIVER,
  ILLUSIONCULUM_SUIT_GOLD_BOXES,
  ILLUSIONCULUM_SUIT_MARKS,
  ILLUSIONCULUM_SUIT_PIECES,
  ILLUSIONCULUM_SUIT_SEAMS,
  ILLUSIONCULUM_SUIT_SIZE,
  ILLUSIONCULUM_SUIT_TILE,
} from "../src/lib/illusionculum-suit.ts";

const dest = resolve(import.meta.dirname, "../src/lib/illusionculum-flights.ts");
const pieces = ILLUSIONCULUM_SUIT_PIECES.map((p) => ({
  ...p,
  preset: ILLUSIONCULUM_SUIT_DRIVER.includes(p.id),
}));
const options = {
  size: ILLUSIONCULUM_SUIT_SIZE,
  pieces,
  core: ILLUSIONCULUM_SUIT_MARKS.core,
  visor: ILLUSIONCULUM_SUIT_MARKS.visor,
  maskTile: ILLUSIONCULUM_SUIT_TILE,
  tile: 12,
};
const plan = planAssembly(options);
const nano = planAssemblyNanites({
  ...options,
  plan,
  staging: ILLUSIONCULUM_ARMOUR_STAGING,
  seams: ILLUSIONCULUM_SUIT_SEAMS,
  goldBoxes: ILLUSIONCULUM_SUIT_GOLD_BOXES,
});
const r = (v, d = 5) => Number(v.toFixed(d));
const rows = nano.pieces
  .filter((p) => !pieces.find((q) => q.id === p.id)?.preset)
  .map((p) => [
    p.id,
    r(p.from),
    r(p.to),
    r(p.depart ?? p.to),
    r(p.contact),
    r(p.offX ?? 0, 2),
    r(p.offY ?? 0, 2),
    r(p.seatHold ?? 0, 3),
    r(p.catchAt ?? 0.3, 3),
    r(p.catchLift ?? 0.5, 3),
    p.ornament ? 1 : 0,
    p.fixed ? 1 : 0,
  ]);
rows.sort((a, b) => a[4] - b[4]);
const raw = `/* Generated by scripts/build-illusionculum-flights.mjs — do not edit.
   Each plate's staged flight as the Rexonance nanite engine plans it for this
   suit with ILLUSIONCULUM_ARMOUR_STAGING, in lock order: id, from, to (the
   plate formed off the body), depart, contact (locked on its seat), the
   lifted offset (figure px), seatHold, catchAt, catchLift, ornament, fixed. */

export type IllusionculumFlight = readonly [
  id: string,
  from: number,
  to: number,
  depart: number,
  contact: number,
  offX: number,
  offY: number,
  seatHold: number,
  catchAt: number,
  catchLift: number,
  ornament: 0 | 1,
  fixed: 0 | 1,
];

export const ILLUSIONCULUM_FLIGHTS: readonly IllusionculumFlight[] = [
${rows.map((row) => `  ${JSON.stringify(row)},`).join("\n")}
];
`;
const text = await format(raw, { ...(await resolveConfig(dest)), filepath: dest });
if (process.argv.includes("--check")) {
  const current = await readFile(dest, "utf8").catch(() => "");
  if (current !== text) {
    console.error(
      "src/lib/illusionculum-flights.ts is stale: run node scripts/build-illusionculum-flights.mjs",
    );
    process.exit(1);
  }
  console.log("illusionculum flights up to date");
} else {
  await writeFile(dest, text);
  console.log(`wrote ${rows.length} flights`);
}
