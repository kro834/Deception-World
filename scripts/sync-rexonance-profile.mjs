import { readFileSync, writeFileSync } from "node:fs";
import { REXONANCE_PROFILE_SECTIONS } from "../src/lib/rexonance-profile.ts";

// One verbatim owner text feeds both the typed rider dossier and the classic
// sandboxed archive script. No extra request or module/CORS permission needed.
const target = new URL("../public/rexonance-archive-update.js", import.meta.url);
const source = readFileSync(target, "utf8");
const marker = / {2}\/\/ BEGIN OWNER_PROFILE_SECTIONS[^\n]*\n[\s\S]*? {2}\/\/ END OWNER_PROFILE_SECTIONS/;
if (!marker.test(source)) throw new Error("Missing owner-profile generated block");
const next = source.replace(marker, () =>
  "  // BEGIN OWNER_PROFILE_SECTIONS (generated by scripts/sync-rexonance-profile.mjs)\n" +
  `  var OWNER_SECTIONS = ${JSON.stringify(REXONANCE_PROFILE_SECTIONS, null, 2).replaceAll("\n", "\n  ")};\n` +
  "  // END OWNER_PROFILE_SECTIONS",
);
if (process.argv.includes("--check")) {
  if (source !== next) throw new Error("Out-of-date Rexonance owner profile; run node scripts/sync-rexonance-profile.mjs");
  console.log("verified Rexonance owner profile");
} else if (source !== next) {
  writeFileSync(target, next, "utf8");
  console.log("synchronized Rexonance owner profile");
}
