// Bake the two sides of a moving studio reflection on three real cell profiles.
// The short lookup table ships with the 2D suit renderer; Three.js stays in the tool.
import { readFile, writeFile } from "node:fs/promises";
import {
  DoubleSide,
  ExtrudeGeometry,
  Group,
  Matrix3,
  Mesh,
  MeshBasicMaterial,
  Raycaster,
  Shape,
  Vector3,
} from "three";

const size = 24;
const material = new MeshBasicMaterial({ side: DoubleSide });
const polar = (r, a) => [r * Math.cos(a), r * Math.sin(a)];
const hex = (r) => Array.from({ length: 6 }, (_, i) => polar(r, Math.PI / 6 + (i * Math.PI) / 3));

function panel(parts, profile, z, depth, bevel, polish, tilt = 0) {
  const shape = new Shape();
  profile.forEach(([x, y], index) => (index ? shape.lineTo(x, y) : shape.moveTo(x, y)));
  shape.closePath();
  const geometry = new ExtrudeGeometry(shape, {
    depth,
    bevelEnabled: true,
    bevelSize: bevel,
    bevelThickness: bevel,
    bevelSegments: 3,
    steps: 1,
  });
  const mesh = new Mesh(geometry, material);
  mesh.position.z = z;
  mesh.rotation.x = tilt;
  mesh.userData.polish = polish;
  parts.add(mesh);
}

function cell(family) {
  const parts = new Group();
  panel(parts, hex(0.88), 0, 0.06, 0.045, 0.25);
  for (let i = 0; i < 6; i++) {
    const a = Math.PI / 6 + (i * Math.PI) / 3;
    if (family === "far-from") {
      // Six folded facets; the open spokes carry the original wireframe.
      panel(
        parts,
        [polar(0.16, a + 0.51), polar(0.77, a + 0.085), polar(0.77, a + 0.955)],
        0.1,
        0.06,
        0.036,
        0.65,
        (i % 2 ? 1 : -1) * 0.055,
      );
    } else if (family === "illusionculum") {
      // Overlapping curved shutter leaves and a recess for the lens.
      panel(
        parts,
        [
          polar(0.35, a + 0.66),
          polar(0.59, a + 0.3),
          polar(0.8, a + 0.04),
          polar(0.78, a + 0.84),
          polar(0.56, a + 1.05),
          polar(0.31, a + 1.18),
        ],
        0.105,
        0.055,
        0.034,
        0.8,
      );
    } else {
      // Alternating lapped armour scales with three raised bridges.
      const radius = i % 2 ? 0.63 : 0.8;
      panel(
        parts,
        [
          polar(0.32, a + 0.18),
          polar(radius, a),
          polar(radius, a + 0.92),
          polar(0.52, a + 1.02),
          polar(0.31, a + 0.73),
        ],
        0.105,
        i % 2 ? 0.048 : 0.1,
        0.032,
        i % 2 ? 0.3 : 0.65,
      );
    }
  }
  if (family !== "far-from")
    panel(parts, hex(family === "illusionculum" ? 0.21 : 0.27), 0.11, 0.09, 0.044, 0.93);
  parts.updateMatrixWorld(true);
  for (const mesh of parts.children)
    mesh.userData.normalMatrix = new Matrix3().getNormalMatrix(mesh.matrixWorld);
  return parts;
}

const key = new Vector3(-0.64, 0.49, 0.58).normalize();
const fill = new Vector3(0.74, 0.24, 0.63).normalize();
const view = new Vector3(0, 0, 1);
const keyHalf = key.clone().add(view).normalize();
const fillHalf = fill.clone().add(view).normalize();
const normal = new Vector3();
const ray = new Raycaster(new Vector3(), new Vector3(0, 0, -1));
const hits = [];

function reflect(hit, light, half) {
  if (!hit) return 0.04;
  normal.copy(hit.normal ?? hit.face.normal).applyNormalMatrix(hit.object.userData.normalMatrix);
  const facing = Math.max(0, normal.dot(light));
  const polish = hit.object.userData.polish;
  const specular = Math.pow(Math.max(0, normal.dot(half)), 6 + 15 * polish);
  return Math.min(1, 0.045 + 0.45 * facing + polish * specular * 0.8 + hit.point.z * 0.2);
}

function bake(name) {
  const parts = cell(name);
  const bytes = Buffer.alloc(size * size);
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let left = 0,
        right = 0;
      for (const dy of [0.25, 0.75]) {
        for (const dx of [0.25, 0.75]) {
          ray.ray.origin.set(((x + dx) * 2) / size - 1, 1 - ((y + dy) * 2) / size, 2);
          hits.length = 0;
          ray.intersectObjects(parts.children, false, hits);
          left += reflect(hits[0], key, keyHalf);
          right += reflect(hits[0], fill, fillHalf);
        }
      }
      bytes[y * size + x] = (Math.round((left * 15) / 4) << 4) | Math.round((right * 15) / 4);
    }
  }
  for (const mesh of parts.children) mesh.geometry.dispose();
  return bytes.toString("base64");
}

const families = ["far-from", "illusionculum", "meta-unitas"];
const table = Object.fromEntries(families.map((name) => [name, bake(name)]));
const output = [
  "// Generated by scripts/build-nanite-relief.mjs from beveled Three.js meshes.",
  "// Each texel contains two 4-bit studio-light samples, left and right.",
  `export const NANITE_RELIEF_SIZE = ${size};`,
  `export const NANITE_RELIEF = ${JSON.stringify(table, null, 2)} as const;`,
  "",
].join("\n");
const destination = new URL("../src/lib/nanite-relief-data.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")) !== output) throw Error("Nanite relief bake differs");
} else {
  await writeFile(destination, output);
}
