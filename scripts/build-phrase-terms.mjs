#!/usr/bin/env node
// Generates src/lib/phrase-terms.generated.js: the site's own proper nouns and
// terms that the generic unit rules (katakana runs, 仮面ライダー…, brackets,
// Latin and number tokens; src/lib/phrase-units.js) would not keep whole:
// kanji names (月城悠真, 夜明護尊), places and coined terms (六詠, 紅魔館,
// 未知結晶状媒介体) and mixed spellings (レルムズフランス本部, コラム01).
//
// Source: the search catalogue (src/components/search/search-data.ts), which
// already gathers every rider, form, character, place and term from the data
// files and canon texts. `--check` fails when the committed file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { runInNewContext } from "node:vm";
import ts from "typescript";
import { withWordBreaks } from "../src/lib/name-break-rules.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const output = resolve(root, "src/lib/phrase-terms.generated.js");

const cache = new Map();
function loadData(absolute) {
  if (cache.has(absolute)) return cache.get(absolute);
  const exports = {};
  cache.set(absolute, exports);
  runInNewContext(
    ts.transpileModule(readFileSync(absolute, "utf8"), {
      compilerOptions: { module: ts.ModuleKind.CommonJS },
    }).outputText,
    {
      exports,
      require: (specifier) =>
        loadData(resolve(dirname(absolute), specifier.endsWith(".ts") ? specifier : `${specifier}.ts`)),
    },
  );
  return exports;
}

/** Name-like pieces of a catalogue string: no sentences, no readings. */
function pieces(value) {
  // A quoted line or a sentence is not a name.
  if (/[、。！？!?…─―]/u.test(String(value))) return [];
  return String(value)
    .replace(/[（(][^）)]*[）)]/gu, " ")
    .split(/[\s\uff0f/×、，,]+/u)
    .map((piece) => piece.replace(/^[『《【「“"']+|[』》】」”"']+$/gu, ""))
    .filter((piece) => {
      const length = [...piece].length;
      return (
        length >= 2 &&
        length <= 10 &&
        // A term carries kanji; kana-only and Latin-only words are rule units.
        /[一-鿿々]/u.test(piece) &&
        // 仮面ライダー… is a rule unit already.
        !/^仮面[゠-ヿ]+$/u.test(piece) &&
        !/[。！？!?…─―「」『』《》【】：:]/u.test(piece) &&
        // Three kana in a row read as a phrase (存在しない), not a name.
        !/[\u3041-\u309f]{3}/u.test(piece)
      );
    });
}

export async function buildPhraseTerms() {
  const { SEARCH_DOCUMENTS } = loadData(resolve(root, "src/components/search/search-data.ts"));
  const named = new Set(["people", "riders", "forms", "world", "systems"]);
  const terms = new Set();
  const stems = new Set();
  for (const document of SEARCH_DOCUMENTS) {
    if (!named.has(document.category)) continue;
    const values = [document.title, ...(document.aliases ?? []), ...(document.keywords ?? [])];
    // A spaced spelling (月城 悠真) also gives each half, which prose uses
    // alone (悠真自身).
    for (const value of values) for (const piece of pieces(value)) terms.add(piece);
    if (!["people", "riders", "forms"].includes(document.category)) continue;
    // The katakana words a long compound is built from (レクソナンス, ファーフロム):
    // where a compound wider than its line may break, at its own joint.
    for (const value of [document.title, ...(document.aliases ?? [])])
      for (const word of withWordBreaks(String(value)).split(/[\u200b\s\u30fb\uff0f/]+/u))
        if (/^[ァ-ヺー]{4,}$/u.test(word) && !/^(?:サーガ|フォーム|ウルトラ|マックス)$/u.test(word))
          stems.add(word);
  }
  const sort = (set) => [...set].sort((a, b) => a.localeCompare(b, "ja"));
  const list = (set) => JSON.stringify(sort(set), null, 0).replaceAll('","', '", "');
  return `// Generated by scripts/build-phrase-terms.mjs from the search catalogue. Do not edit.\nexport const PHRASE_TERMS = ${list(terms)};\nexport const PHRASE_STEMS = ${list(stems)};\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await buildPhraseTerms();
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== next) {
      console.error("phrase-terms.generated.js is stale: run node scripts/build-phrase-terms.mjs");
      process.exitCode = 1;
    }
  } else writeFileSync(output, next, "utf8");
}
