import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildRealmArchiveMotion } from "./build-realm-archive-motion.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const mediaDirectory = resolve(root, "public/archive-media");
const stabilityStylesheet =
  '<link rel="stylesheet" href="/archive-mobile-stability.css?v=20261009-r51">';
const stabilityScript = '<script src="/archive-scroll-stability.js?v=20260930-r48" defer></script>';
// Reports the archive's titles and fixed controls to the page, so the
// floating Zeus button keeps off them inside this sandboxed frame too.
const zeusBridgeScript = '<script src="/archive-zeus-bridge.js?v=20260928-z1" defer></script>';
// Carries the reader's form and compared pair between the page URL and this
// sandboxed frame (the page passes them in the frame's #fragment).
const stateBridgeScript = '<script src="/archive-state-bridge.js?v=20261009-s1" defer></script>';
const nameWordAssets = '<link rel="stylesheet" href="/name-words.css?v=20261006-names">\n<script src="/archive-name-words.generated.js?v=20261006-names" defer></script>';
// The frame intentionally has an opaque sandbox origin. Classic scripts
// preserve that boundary; ES module fetches would require CORS permission.
const nameRules = readFileSync(resolve(root, "src/lib/name-break-rules.js"), "utf8").replace(/^export /gm, "");
const nameEnhancer = readFileSync(resolve(root, "src/lib/archive-name-words.js"), "utf8").replace(/^import[^\n]*\n/, "");
writeFileSync(resolve(root, "public/name-words.css"), readFileSync(resolve(root, "src/styles-name-words.css"), "utf8"));
writeFileSync(resolve(root, "public/archive-name-words.generated.js"), `// Generated by build-embedded-archives.mjs from the shared name rule sources.\n(() => {\n"use strict";\n${nameRules}\n${nameEnhancer}\n})();\n`);
const archives = [
  {
    kind: "saga",
    source: resolve(root, "archives/saga-form-archive-standalone.html"),
    output: resolve(root, "public/saga-form-archive-embedded.html"),
  },
  {
    kind: "realm",
    source: resolve(root, "archives/realm-form-archive-standalone.html"),
    output: resolve(root, "public/realm-form-archive-embedded.html"),
  },
];

const extensions = new Map([
  ["jpeg", "jpg"],
  ["jpg", "jpg"],
  ["png", "png"],
  ["webp", "webp"],
  ["gif", "gif"],
  ["avif", "avif"],
]);

mkdirSync(mediaDirectory, { recursive: true });
if (existsSync(resolve(root, "archives/saga-form-archive-standalone.html"))) {
  buildRealmArchiveMotion();
} else {
  console.log("[embedded-archive] source archives missing; keeping committed embedded HTML");
}

for (const archive of archives) {
  if (!existsSync(archive.source)) {
    if (!existsSync(archive.output)) {
      throw new Error(`Missing archive source and output for ${archive.kind}`);
    }
    console.log(`[embedded-archive] ${archive.kind}: skipped (source not in deploy context)`);
    continue;
  }
  const source = readFileSync(archive.source, "utf8");
  let imageCount = 0;
  const output = source.replace(
    /data:image\/([a-zA-Z0-9.+-]+);base64,([A-Za-z0-9+/=]+)/g,
    (dataUri, mime, encoded) => {
      const extension = extensions.get(mime.toLowerCase());
      if (!extension) return dataUri;
      const decoded = Buffer.from(encoded, "base64");
      const hash = createHash("sha256").update(decoded).digest("hex").slice(0, 16);
      const filename = `${archive.kind}-${hash}.${extension}`;
      writeFileSync(resolve(mediaDirectory, filename), decoded);
      imageCount += 1;
      return `/archive-media/${filename}`;
    },
  );

  const withEmbeddedMarker = output.replace(
    /<html\b([^>]*)>/,
    `<html$1 data-embedded-archive="true" data-archive-kind="${archive.kind}">`,
  );
  const withMobileStyles = withEmbeddedMarker.includes(stabilityStylesheet)
    ? withEmbeddedMarker
    : withEmbeddedMarker.replace("</head>", `${stabilityStylesheet}\n</head>`);
  const withScrollStability = withMobileStyles.includes(stabilityScript)
    ? withMobileStyles
    : withMobileStyles.replace("</head>", `${stabilityScript}\n</head>`);
  const withZeusBridge = withScrollStability.includes(zeusBridgeScript)
    ? withScrollStability
    : withScrollStability.replace("</head>", `${zeusBridgeScript}\n</head>`);
  const readySignal = `<script data-archive-ready-signal>
(() => {
  const announceReady = () => {
    document.documentElement.dataset.archiveReadySignal = "scheduled";
    window.requestAnimationFrame(() => window.requestAnimationFrame(() => {
      window.parent.postMessage({
        type: "saga-archive:ready",
        kind: document.documentElement.dataset.archiveKind
      }, "*");
      document.documentElement.dataset.archiveReadySignal = "sent";
    }));
  };
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", announceReady, { once: true });
  } else {
    announceReady();
  }
})();
</script>`;
  const withStateBridge = withZeusBridge.includes(stateBridgeScript)
    ? withZeusBridge
    : withZeusBridge.replace("</head>", `${stateBridgeScript}\n</head>`);
  const withNameWords = withStateBridge.includes(nameWordAssets)
    ? withStateBridge
    : withStateBridge.replace("</head>", `${nameWordAssets}\n</head>`);
  const withReadySignal = withNameWords.includes("data-archive-ready-signal")
    ? withNameWords
    : withNameWords.replace("</body>", `${readySignal}\n</body>`);

  writeFileSync(archive.output, withReadySignal);
  console.log(
    `[embedded-archive] ${archive.kind}: externalized ${imageCount} image references; ${Buffer.byteLength(withReadySignal)} byte HTML`,
  );
}
