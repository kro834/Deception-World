const file = (path) => fileURLToPath(new URL(`../${path}`, import.meta.url));
const publicFile = (src) => file(`public${src}`);
const moduleText = readFileSync(file("src/lib/far-from-nanites.ts"), "utf8");
const C = FAR_FROM_NANITE_CELLS;
const N = C.cell;
const decode = async (src) => {
  const { data, info } = await sharp(publicFile(src))
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  return { data, width: info.width, height: info.height };
};
const sheet = decode(C.src);
const luminance = (d, i) => (0.2126 * d[i] + 0.7152 * d[i + 1] + 0.0722 * d[i + 2]) / 255;
/** Alpha-weighted mean luminance of a cell, optionally over a region of
 * centred cell coordinates. */
const meanLight = ({ data, width }, x0, y0, region = () => true, n = N) => {
  let [sum, weight] = [0, 0];
  for (let y = 0; y < n; y += 1)
    for (let x = 0; x < n; x += 1) {
      if (!region(x + 0.5 - n / 2, y + 0.5 - n / 2)) continue;
      const i = ((y0 + y) * width + x0 + x) * 4;
      const a = data[i + 3] / 255;
      sum += luminance(data, i) * a;
      weight += a;
    }
  return weight ? sum / weight : 0;
};
const coverage = ({ data, width }, x0, y0, n = N, at = 128) => {
  let count = 0;
  for (let y = 0; y < n; y += 1)
    for (let x = 0; x < n; x += 1) if (data[((y0 + y) * width + x0 + x) * 4 + 3] >= at) count += 1;
  return count;
};
// Every sprite of the sheet: [name, x, y, size].
const sprites = () => {
  const list = [];
  for (let t = 0; t < 4; t += 1)
    for (let f = 0; f < C.frames; f += 1) {
      list.push([`tumble ${t}/${f}`, N * f, N * t, N]);
      list.push([`mip ${t}/${f}`, C.mip.x[t] + C.mip.cell * f, C.mip.y[t], C.mip.cell]);
    }
  for (let t = 0; t < 3; t += 1)
    for (let k = 0; k < C.unfold.frames; k += 1)
      list.push([`unfold ${t}/${k}`, C.unfold.x[t] + N * k, C.unfold.y, N]);
  for (let t = 0; t < 4; t += 1) list.push([`bokeh ${t}`, C.bokeh.x[t], C.bokeh.y[t], N]);
  for (let k = 0; k < C.bead.frames; k += 1)
    list.push([`bead ${k}`, C.bead.x + N * k, C.bead.y, N]);
  for (let k = 0; k < C.spark.frames; k += 1)
    list.push([`spark ${k}`, C.spark.x + N * k, C.spark.y, N]);
  return list;
};

test("the kit's folder holds exactly its one sheet, at its size and within budget", async () => {
  assert.equal(FAR_FROM_NANITE_DIR, "/far-from-nanites-20261022");
  assert.deepEqual(readdirSync(publicFile(FAR_FROM_NANITE_DIR)), ["cells.webp"]);
  assert.equal(C.src, `${FAR_FROM_NANITE_DIR}/cells.webp`);
  const meta = await sharp(publicFile(C.src)).metadata();
  assert.equal(meta.format, "webp");
  assert.deepEqual([meta.width, meta.height, meta.channels], [C.width, C.height, 4]);
  const bytes = statSync(publicFile(C.src)).size;
  assert.equal(FAR_FROM_NANITE_BYTES.cells, bytes, "BYTES is the file's size");
  assert.equal(FAR_FROM_NANITE_BYTES.total, bytes);
  assert.ok(bytes <= 96_000, `cells.webp ${bytes} B within 96,000`);
  assert.ok(bytes < 300_000, "the kit stays well under 300 KB");
  assert.deepEqual(FAR_FROM_NANITE_ASSETS, [C.src]);
});

