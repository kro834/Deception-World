test("its cells follow kit A's layout contract exactly: same keys, cell, frames, slots and sub-sheets", () => {
  const shape = (value) =>
    Array.isArray(value)
      ? value.map(shape)
      : value && typeof value === "object"
        ? Object.fromEntries(Object.entries(value).map(([key, v]) => [key, shape(v)]))
        : typeof value;
  // Key for key, in the same order, the same types.
  assert.equal(JSON.stringify(shape(C)), JSON.stringify(shape(REXONANCE_NANITE_CELLS)));
  const { src: ours, ...geometry } = C;
  const { src: theirs, ...contract } = REXONANCE_NANITE_CELLS;
  assert.notEqual(ours, theirs, "its own sheet");
  assert.deepEqual(geometry, contract, "every sprite where kit A's sprite code looks for it");
  assert.equal(C.cell, 32);
  assert.equal(C.frames, 24);
  assert.equal(C.lockFrame, 0);
  assert.equal(C.mip.cell, 16);
  assert.equal(C.unfold.frames, 7);
  assert.equal(C.bead.frames, 8);
  assert.equal(C.spark.frames, 4);
  // No comets of its own: the swarm draws kit A's, whose rows serve the
  // same tone slots.
  assert.deepEqual(Object.keys(REXONANCE_NANITE_COMETS.rows), ["ice", "pink", "gold"]);
  assert.match(moduleText, /REXONANCE_NANITE_COMETS/);
});

test("every sprite region lies inside the sheet and no two overlap", () => {
  const regions = sprites();
  for (const [name, x, y, n] of regions)
    assert.ok(x >= 0 && y >= 0 && x + n <= C.width && y + n <= C.height, `${name} inside`);
  for (let i = 0; i < regions.length; i += 1)
    for (let j = i + 1; j < regions.length; j += 1) {
      const [a, ax, ay, an] = regions[i];
      const [b, bx, by, bn] = regions[j];
      assert.ok(
        ax + an <= bx || bx + bn <= ax || ay + an <= by || by + bn <= ay,
        `${a} and ${b} overlap`,
      );
    }
});

test("a transparent sheet: every sprite on clear alpha, the tumble's corners and the unused space empty", async () => {
  const s = await sheet;
  const used = new Uint8Array(C.width * C.height);
  for (const [name, x0, y0, n] of sprites()) {
    const least = name.startsWith("spark") ? 3 : n === 16 ? 6 : 20;
    assert.ok(coverage(s, x0, y0, n, 32) >= least, `${name} has its sprite`);
    for (let y = 0; y < n; y += 1)
      used.fill(1, (y0 + y) * C.width + x0, (y0 + y) * C.width + x0 + n);
  }
  let stray = 0;
  for (let i = 0; i < used.length; i += 1) if (!used[i] && s.data[i * 4 + 3]) stray += 1;
  assert.equal(stray, 0, "nothing outside the sprites");
  // The crystal turns within the circle its tips reach (≤ 16 px from the
  // centre): each tumble cell's 3 × 3 corners stay clear.
  for (let t = 0; t < 4; t += 1)
    for (let f = 0; f < C.frames; f += 1)
      for (const [cx, cy] of [
        [0, 0],
        [N - 3, 0],
        [0, N - 3],
        [N - 3, N - 3],
      ])
        for (let y = 0; y < 3; y += 1)
          for (let x = 0; x < 3; x += 1)
            assert.equal(
              s.data[((N * t + cy + y) * C.width + N * f + cx + x) * 4 + 3],
              0,
              `tumble ${t}/${f} corner`,
            );
});

test("premultiplied edges: no dark fringe round any sprite", async () => {
  // Each silhouette pixel (alpha 8–159, a transparent 4-neighbour) is the
  // same surface as its solid 8-neighbours (alpha ≥ 160), so about as
  // bright. A colour darkened by the transparent black round it — straight
  // alpha resized or encoded unpremultiplied — keeps only about its alpha's
  // share of their light (≈ 0.1–0.5 here; such a sheet scores 0.25 overall).
  const { data, width, height } = await sheet;
  const alpha = (x, y) =>
    x < 0 || y < 0 || x >= width || y >= height ? 0 : data[(y * width + x) * 4 + 3];
  const bands = Array.from({ length: 5 }, () => [0, 0]);
  let [edgeLight, innerLight, count, dark] = [0, 0, 0, 0];
  for (let y = 0; y < height; y += 1)
    for (let x = 0; x < width; x += 1) {
      const a = alpha(x, y);
      if (a < 8 || a >= 160) continue;
      if (alpha(x - 1, y) && alpha(x + 1, y) && alpha(x, y - 1) && alpha(x, y + 1)) continue;
      let [sum, weight] = [0, 0];
      for (let dy = -1; dy <= 1; dy += 1)
        for (let dx = -1; dx <= 1; dx += 1) {
          const b = alpha(x + dx, y + dy);
          if (b < 160) continue;
          sum += luminance(data, ((y + dy) * width + x + dx) * 4) * b;
          weight += b;
        }
      if (!weight) continue;
      const L = luminance(data, (y * width + x) * 4);
      const M = sum / weight;
      edgeLight += L;
      innerLight += M;
      bands[a >> 5][0] += L;
      bands[a >> 5][1] += M;
      count += 1;
      if (L < 0.45 * M) dark += 1;
    }
  assert.ok(count > 2000, `${count} edge pixels`);
  assert.ok(
    edgeLight / innerLight >= 0.8,
    `edges keep ${(edgeLight / innerLight).toFixed(3)} of their neighbours' light`,
  );
  for (const [band, [L, M]] of bands.entries())
    assert.ok(
      L / M >= 0.7,
      `alpha ${band * 32}–${band * 32 + 31}: edges keep ${(L / M).toFixed(2)} of their neighbours' light`,
    );
  assert.ok(
    dark <= 0.15 * count,
    `${dark} of ${count} edge pixels under 45% of their neighbours' light`,
  );
});

test("the crystal: a tall rhombus, its core outshining its rim, its back dark but lit, an unfolding plate", async () => {
  const s = await sheet;
  const { data, width } = s;
  for (let t = 0; t < 4; t += 1) {
    // f0's silhouette: much taller than wide, filling about half its box
    // (a rhombus; the hex chip fills three quarters of a squat one).
    let [x0, y0, x1, y1, area] = [N, N, -1, -1, 0];
    for (let y = 0; y < N; y += 1)
      for (let x = 0; x < N; x += 1) {
        if (data[((N * t + y) * width + x) * 4 + 3] < 128) continue;
        [x0, y0, x1, y1] = [Math.min(x0, x), Math.min(y0, y), Math.max(x1, x), Math.max(y1, y)];
        area += 1;
      }
    const [w, h] = [x1 - x0 + 1, y1 - y0 + 1];
    assert.ok(h >= 28 && h >= 1.6 * w, `tone ${t}: f0 is ${w} × ${h} px`);
    assert.ok(
      area / (w * h) > 0.45 && area / (w * h) < 0.65,
      `tone ${t}: f0 fills ${((100 * area) / (w * h)).toFixed(0)}% of its box`,
    );
    const centre = meanLight(s, 0, N * t, (x, y) => Math.hypot(x, y) < 3);
    const rim = meanLight(s, 0, N * t, (x, y) => Math.hypot(x, y) > 8);
    assert.ok(
      centre > rim + 0.1,
      `tone ${t}: the lock pose's core (${centre.toFixed(2)}) outshines its rim (${rim.toFixed(2)})`,
    );
    const f0 = meanLight(s, 0, N * t);
    for (let f = 10; f <= 14; f += 1) {
      const back = meanLight(s, N * f, N * t);
      assert.ok(
        back < f0 && back > 8 / 255,
        `tone ${t} frame ${f}: the back ${back.toFixed(3)} (face ${f0.toFixed(3)})`,
      );
    }
  }
  for (let t = 0; t < 3; t += 1) {
    const x0 = C.unfold.x[t];
    let opaque = 0;
    for (let y = 2; y < 30; y += 1)
      for (let x = 2; x < 30; x += 1)
        if (data[((C.unfold.y + y) * width + x0 + N * 6 + x) * 4 + 3] >= 240) opaque += 1;
    assert.ok(opaque >= 0.85 * 28 * 28, `tone ${t}: the unfolded plate covers ${opaque} of 784 px`);
    let diff = 0;
    for (let y = 0; y < N; y += 1)
      for (let x = 0; x < N; x += 1) {
        const k = ((C.unfold.y + y) * width + x0 + x) * 4;
        const f = ((N * t + y) * width + x) * 4;
        for (let c = 0; c < 3; c += 1)
          diff += Math.abs((data[k + c] * data[k + 3]) / 255 - (data[f + c] * data[f + 3]) / 255);
        diff += Math.abs(data[k + 3] - data[f + 3]);
      }
    assert.ok(
      diff / (N * N * 4) <= 3,
      `tone ${t}: unfold k0 is tumble f0 (mean difference ${(diff / (N * N * 4)).toFixed(2)})`,
    );
  }
});

test("each tone reads as its crystal: aqua, lilac prism, colourless silver, amber gold", async () => {
  const s = await sheet;
  const { data, width } = s;
  const hue = (t) => {
    const sum = [0, 0, 0];
    for (let y = 0; y < N; y += 1)
      for (let x = 0; x < N; x += 1) {
        const i = ((N * t + y) * width + x) * 4;
        for (let c = 0; c < 3; c += 1) sum[c] += data[i + c] * (data[i + 3] / 255);
      }
    return sum;
  };
  const [aqua, prism, silver, gold] = [0, 1, 2, 3].map(hue);
  assert.ok(aqua[2] > 1.25 * aqua[0] && aqua[1] > 1.15 * aqua[0], `aqua ${aqua.map(Math.round)}`);
  assert.ok(prism[2] > prism[1] && prism[0] > 1.05 * prism[1], `prism ${prism.map(Math.round)}`);
  assert.ok(Math.max(...silver) < 1.25 * Math.min(...silver), `silver ${silver.map(Math.round)}`);
  assert.ok(gold[0] > 1.1 * gold[1] && gold[1] > 1.3 * gold[2], `gold ${gold.map(Math.round)}`);
});

test("the 16 px mips are the same frames, and the spark and bead keep their contracts", async () => {
  const s = await sheet;
  const { data, width } = s;
  for (let t = 0; t < 4; t += 1)
    for (let f = 0; f < C.frames; f += 1) {
      const big = coverage(s, N * f, N * t, N, 128);
      const small = coverage(s, C.mip.x[t] + C.mip.cell * f, C.mip.y[t], C.mip.cell, 128);
      assert.ok(
        Math.abs(4 * small - big) <= 0.3 * big + 8,
        `mip ${t}/${f}: ${small} px for ${big}`,
      );
    }
  // The spark: frame 0 the largest and brightest, its brightest pixel (16, 16).
  const light = (k) => {
    let [sum, max, at] = [0, 0, null];
    for (let y = 0; y < N; y += 1)
      for (let x = 0; x < N; x += 1) {
        const i = ((C.spark.y + y) * width + C.spark.x + N * k + x) * 4;
        const v = luminance(data, i) * data[i + 3];
        sum += v;
        if (v > max) [max, at] = [v, [x, y]];
      }
    return { sum, max, at };
  };
  const frames = [0, 1, 2, 3].map(light);
  for (let k = 1; k < 4; k += 1)
    assert.ok(frames[k].sum < frames[k - 1].sum, `spark frame ${k} is smaller than ${k - 1}`);
  const centre =
    luminance(data, ((C.spark.y + 16) * width + C.spark.x + 16) * 4) *
    data[((C.spark.y + 16) * width + C.spark.x + 16) * 4 + 3];
  assert.ok(
    centre >= frames[0].max - 2,
    `the spark's centre (16, 16) is its brightest (${frames[0].at})`,
  );
  // The bead: molten gold, alone (no stray scene parts round it).
  for (let k = 0; k < C.bead.frames; k += 1) {
    let [gold, cool] = [0, 0];
    for (let y = 0; y < N; y += 1)
      for (let x = 0; x < N; x += 1) {
        const i = ((C.bead.y + y) * width + C.bead.x + N * k + x) * 4;
        if (data[i + 3] < 128) continue;
        if (data[i] >= data[i + 1] && data[i + 1] >= data[i + 2]) gold += 1;
        else if (data[i + 2] > data[i]) cool += 1;
      }
    assert.ok(gold >= 100 && cool === 0, `bead ${k}: ${gold} gold, ${cool} cool pixels`);
  }
});

