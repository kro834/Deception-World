import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import sharp from "sharp";

// One representative, using the existing published native-size image. Never upscale.
const root = new URL("../", import.meta.url);
const catalogue = JSON.parse(await readFile(new URL("public/gallery/asset-manifest.json", root)));
const work = catalogue.items.find(({ id }) => id === "g68");
const full = work.variants.at(-1);
const source = await readFile(new URL(`public${full.path}`, root));
const hash = (bytes) => createHash("sha256").update(bytes).digest("hex");
const directory = new URL("public/gallery/detail/g68/", root);
await mkdir(directory, { recursive: true });
const tiles = [];
let squaredError = 0;
let samples = 0;
for (let top = 0; top < work.sourceHeight; top += 336) {
  for (let left = 0; left < work.sourceWidth; left += 448) {
    const region = {
      left,
      top,
      width: Math.min(448, work.sourceWidth - left),
      height: Math.min(336, work.sourceHeight - top),
    };
    const original = await sharp(source).extract(region).removeAlpha().raw().toBuffer();
    const bytes = await sharp(source).extract(region).webp({ quality: 90, effort: 6 }).toBuffer();
    const decoded = await sharp(bytes).removeAlpha().raw().toBuffer();
    for (let index = 0; index < decoded.length; index++)
      squaredError += (original[index] - decoded[index]) ** 2;
    samples += decoded.length;
    const name = `${left}-${top}.webp`;
    await writeFile(new URL(name, directory), bytes);
    tiles.push({
      ...region,
      path: `/gallery/detail/g68/${name}`,
      bytes: bytes.length,
      sha256: hash(bytes),
    });
  }
}
const manifest = {
  id: work.id,
  width: work.sourceWidth,
  height: work.sourceHeight,
  source: full.path,
  sourceBytes: source.length,
  sourceSha256: hash(source),
  encoder: { format: "webp", quality: 90, effort: 6, withoutEnlargement: true },
  comparison: {
    reference: "published native-size WebP decoded to RGB",
    psnrDb: 10 * Math.log10(255 ** 2 / (squaredError / samples)),
    rmse: Math.sqrt(squaredError / samples),
  },
  tiles,
};
await writeFile(new URL("manifest.json", directory), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(
  new URL("src/components/gallery/gallery-detail-assets.ts", root),
  `// Generated by scripts/build-gallery-detail.mjs; coordinates are source pixels.\nexport const GALLERY_DETAIL = ${JSON.stringify(manifest, null, 2)} as const;\n`,
);
console.log(
  JSON.stringify({
    tiles: tiles.length,
    totalBytes: tiles.reduce((sum, tile) => sum + tile.bytes, 0),
    sourceBytes: source.length,
    ...manifest.comparison,
  }),
);
